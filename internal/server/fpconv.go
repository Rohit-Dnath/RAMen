func fpFindCachedPow10(exp int) (fp, int) {
	const oneLogTen = 0.30102999566398114
	approx := int(float64(-(exp + fpNPowers)) * oneLogTen)
	idx := (approx - fpFirstPower) / fpStepPowers
	for {
		current := exp + fpPowersTen[idx].exp + 64
		if current < fpExpMin {
			idx++
			continue
		}
		if current > fpExpMax {
			idx--
			continue
		}
		return fpPowersTen[idx], fpFirstPower + idx*fpStepPowers
	}
}

func fpBuild(d float64) fp {
	bits := math.Float64bits(d)
	f := fp{frac: bits & fpFracMask, exp: int((bits & fpExpMask) >> 52)}
	if f.exp != 0 {
		f.frac += fpHiddenBit
		f.exp -= fpExpBias
	} else {
		f.exp = -fpExpBias + 1
	}
	return f
}

func fpNormalize(f *fp) {
	for f.frac&fpHiddenBit == 0 {
		f.frac <<= 1
		f.exp--
	}
	const shift = 64 - 52 - 1
	f.frac <<= shift
	f.exp -= shift
}

func fpBoundaries(f fp) (lower, upper fp) {
	upper.frac = (f.frac << 1) + 1
	upper.exp = f.exp - 1
	for upper.frac&(fpHiddenBit<<1) == 0 {
		upper.frac <<= 1
		upper.exp--
	}
	const uShift = 64 - 52 - 2
	upper.frac <<= uShift
	upper.exp -= uShift

	lShift := 1
	if f.frac == fpHiddenBit {
		lShift = 2
	}
	lower.frac = (f.frac << lShift) - 1
	lower.exp = f.exp - lShift
	lower.frac <<= uint(lower.exp - upper.exp)
	lower.exp = upper.exp
	return lower, upper
}

func fpMultiply(a, b fp) fp {
	const lomask = 0x00000000FFFFFFFF
	ahBl := (a.frac >> 32) * (b.frac & lomask)
	alBh := (a.frac & lomask) * (b.frac >> 32)
	alBl := (a.frac & lomask) * (b.frac & lomask)
	ahBh := (a.frac >> 32) * (b.frac >> 32)

	tmp := (ahBl & lomask) + (alBh & lomask) + (alBl >> 32)
	tmp += 1 << 31 // round up
	return fp{ahBh + (ahBl >> 32) + (alBh >> 32) + (tmp >> 32), a.exp + b.exp + 64}
}

func fpRoundDigit(digits []byte, delta, rem, kappa, frac uint64) {
	for rem < frac && delta-rem >= kappa &&
		(rem+kappa < frac || frac-rem > rem+kappa-frac) {
		digits[len(digits)-1]--
		rem += kappa
	}
}

func fpGenerateDigits(w, upper, lower fp, K *int) []byte {
	wfrac := upper.frac - w.frac
	delta := upper.frac - lower.frac
	shift := uint(-upper.exp)
	one := uint64(1) << shift

	part1 := upper.frac >> shift
	part2 := upper.frac & (one - 1)

	digits := make([]byte, 0, 18)
	kappa := 10
	for i := 10; kappa > 0; i++ { // fpTens[10] == 1000000000
		div := fpTens[i]
		digit := part1 / div
		if digit != 0 || len(digits) > 0 {
			digits = append(digits, byte(digit)+'0')
		}
		part1 -= digit * div
		kappa--

		if tmp := (part1 << shift) + part2; tmp <= delta {
			*K += kappa
			fpRoundDigit(digits, delta, tmp, div<<shift, wfrac)
			return digits
		}
	}

	for unit := 18; ; unit-- { // fpTens[18] == 10
		part2 *= 10
		delta *= 10
		kappa--

		digit := part2 >> shift
		if digit != 0 || len(digits) > 0 {
			digits = append(digits, byte(digit)+'0')
		}
		part2 &= one - 1
		if part2 < delta {
			*K += kappa
			fpRoundDigit(digits, delta, part2, one, wfrac*fpTens[unit])
			return digits
		}
	}
}

// fpGrisu2 returns the digits of d (> 0, finite) and K such that
// d ≈ digits * 10^K.
func fpGrisu2(d float64) ([]byte, int) {
	w := fpBuild(d)
	lower, upper := fpBoundaries(w)
	fpNormalize(&w)

	cp, k := fpFindCachedPow10(upper.exp)
	w = fpMultiply(w, cp)
	upper = fpMultiply(upper, cp)
	lower = fpMultiply(lower, cp)
	lower.frac++
	upper.frac--

	K := -k
	digits := fpGenerateDigits(w, upper, lower, &K)
	return digits, K
}

// fpconvDtoa formats a finite, non-zero d like Redis's fpconv_dtoa: plain
// digits when that stays short, d1.d2..dne±X otherwise.
func fpconvDtoa(d float64) string {
	b := make([]byte, 0, 24)
	neg := d < 0
	if neg {
		b = append(b, '-')
		d = -d
	}
	digits, K := fpGrisu2(d)
	nd := len(digits)
	exp := K + nd - 1 // exponent of the first digit
	absExp := exp
	if absExp < 0 {
		absExp = -absExp
	}

	switch {
	case K >= 0 && absExp < nd+7: // plain integer
		b = append(b, digits...)
		for i := 0; i < K; i++ {
			b = append(b, '0')
		}
	case K < 0 && (K > -7 || absExp < 4): // decimal without exponent
		if offset := nd + K; offset <= 0 {
			b = append(b, '0', '.')
			for i := 0; i < -offset; i++ {
				b = append(b, '0')
			}
			b = append(b, digits...)
		} else {
			b = append(b, digits[:offset]...)
			b = append(b, '.')
			b = append(b, digits[offset:]...)
		}
	default: // scientific, exponent without zero padding
		maxDigits := 18
		if neg {
			maxDigits = 17
		}
		if nd > maxDigits {
			nd = maxDigits
		}
		b = append(b, digits[0])
		if nd > 1 {
			b = append(b, '.')
			b = append(b, digits[1:nd]...)
		}
		b = append(b, 'e')
		if K+nd-1 < 0 {
			b = append(b, '-')
		} else {
			b = append(b, '+')
		}
		b = appendInt(b, absExp)
	}
	return string(b)
}

func appendInt(b []byte, n int) []byte {
	if n >= 10 {
		b = appendInt(b, n/10)
	}
	return append(b, byte(n%10)+'0')
}
