package server

import (
	"strconv"
	"testing"
)

// Every want value below is a real Redis 8.10 ZSCORE reply after ZADD-ing the
// input, so this pins Redis's actual output rather than our reading of it.
func TestFormatFloatMatchesRedis(t *testing.T) {
	cases := []struct{ in, want string }{
		// whole numbers within ±2^62 print as integers, never 1e+06
		{"1000000", "1000000"},
		{"-1000000", "-1000000"},
		{"100.0", "100"},
		{"1e18", "1000000000000000000"},
		{"4611686018427387904", "4611686018427387904"}, // 2^62, the last integer-path value
		{"4611686018427387905", "4611686018427387904"}, // rounds to 2^62 as a double
		{"4611686018427388928", "4611686018427389000"}, // just past 2^62: fpconv path
		{"-4611686018427387904", "-4611686018427387904"},
		{"-4611686018427388928", "-4611686018427389000"},
		{"9007199254740993", "9007199254740992"},
		{"123456789012345678", "123456789012345680"},
		{"123.456e5", "12345600"},
		{"1.5e10", "15000000000"},

		// fractions
		{"7.5", "7.5"},
		{"0.1", "0.1"},
		{"-0.1", "-0.1"},
		{"0.3333333333333333", "0.3333333333333333"},
		{"1000000.5", "1000000.5"},
		{"99999999999.5", "99999999999.5"},
		{"123456789.123", "123456789.123"},

		// small magnitudes: plain down to 1e-6, then exponent without padding
		{"0.0001", "0.0001"},
		{"1e-5", "0.00001"},
		{"1e-6", "0.000001"},
		{"1e-7", "1e-7"},
		{"-1e-7", "-1e-7"},
		{"0.0000012345", "1.2345e-6"},
		{"1.23456789012345e-10", "1.23456789012345e-10"},
		{"1e-100", "1e-100"},
		{"2.2250738585072014e-308", "2.2250738585072014e-308"},
		{"5e-324", "5e-324"},

		// large magnitudes past 2^62
		{"1e19", "1e+19"},
		{"2.5e20", "2.5e+20"},
		{"1.5e25", "1.5e+25"},
		{"12345678901234567e3", "12345678901234567000"},
		{"12345678901234567e7", "123456789012345670000000"},
		{"1e100", "1e+100"},
		{"1.7976931348623157e308", "1.7976931348623157e+308"},

		// grisu2 is not always shortest; Redis prints these extra digits
		{"1e23", "99999999999999990000000"},
		{"-81.262594", "-81.26259400000001"},
		{"92265754e12", "92265753999999990000"},
		{"1.1212166857430032e+15", "1121216685743003.3"},
		{"-5.705004189984573e-117", "-5.7050041899845734e-117"},
		{"2.106208983047083e+21", "2106208983047083100000"},

		// specials; a sorted set reports -0 as "0"
		{"0", "0"},
		{"-0", "0"},
		{"inf", "inf"},
		{"+inf", "inf"},
		{"-inf", "-inf"},
	}
	for _, tc := range cases {
		f, err := strconv.ParseFloat(tc.in, 64)
		if err != nil {
			t.Fatalf("bad test input %q: %v", tc.in, err)
		}
		if got := formatFloat(f); got != tc.want {
			t.Errorf("formatFloat(%s) = %q, want %q", tc.in, got, tc.want)
		}
	}
}
